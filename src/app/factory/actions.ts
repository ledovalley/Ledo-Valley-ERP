export async function savePacketProduct(product: {
  id?: string;
  name: string;
  unit: string;
  size: number;
  hsnCode?: string;
  gstRate?: number;
  /** Only for corrections from the edit form: the stock the user saw, and the new value. */
  stock?: number;
  expectedStock?: number;
}): Promise<ActionResult<{ id: string; stock?: number }>> {
  try {
    const { user, role, userName } = await enforceFactoryAccess();
    if (!['admin', 'manager'].includes(role)) {
      return { error: 'Only admins and managers can modify factory product templates.' };
    }

    const name = required(product.name, 'Product name');
    const unit = required(product.unit || 'KG', 'Unit');
    const size = positive(product.size, 'Pack size');
    const gstRate = product.gstRate === undefined ? 5 : nonNegative(product.gstRate, 'GST rate');
    const fields = {
      name,
      unit,
      size,
      hsn_code: (product.hsnCode || '').trim(),
      gst_rate: gstRate,
      updated_at: new Date().toISOString()
    };

    // New product: always starts at zero stock. Stock arrives through receipts or packing.
    if (!product.id) {
      const id = newId('p');
      const { error } = await supabaseAdmin.from('factory_packet_catalog').insert({ id, ...fields, stock: 0 });
      if (error) return { error: error.message };

      await writeHistory({
        type: 'PACKET_TEMPLATE_CREATED',
        description: `Created packet template: ${name} (${size} kg/${unit})`,
        userId: user.id,
        userName,
        details: { productId: id, ...fields }
      });
      revalidatePath('/factory');
      return { success: true, id };
    }

    if (product.id === 'p-variance') {
      return { error: 'The system variance ledger cannot be edited.' };
    }

    // Existing product: update details only. Never overwrite stock from the browser's copy.
    const { data: updated, error } = await supabaseAdmin
      .from('factory_packet_catalog')
      .update(fields)
      .eq('id', product.id)
      .select('id, stock')
      .maybeSingle();
    if (error) return { error: error.message };
    if (!updated) return { error: 'Product not found. It may have been deleted.' };

    let stock = Number(updated.stock);

    // Optional stock correction: only applies if nobody changed the stock since the form opened.
    if (product.stock !== undefined && product.expectedStock !== undefined && product.stock !== product.expectedStock) {
      const newStock = nonNegative(product.stock, 'Stock');
      const { data: corrected, error: stockErr } = await supabaseAdmin
        .from('factory_packet_catalog')
        .update({ stock: newStock, updated_at: new Date().toISOString() })
        .eq('id', product.id)
        .eq('stock', product.expectedStock)
        .select('stock')
        .maybeSingle();
      if (stockErr) return { error: stockErr.message };
      if (!corrected) {
        return { error: `Details saved, but stock was NOT changed: it was updated by someone else (now ${stock}). Refresh and try again.` };
      }
      await writeHistory({
        type: 'PACKET_STOCK_CORRECTED',
        description: `Corrected stock of "${name}" from ${product.expectedStock} to ${newStock}.`,
        userId: user.id,
        userName,
        details: { productId: product.id, productName: name, prevStock: product.expectedStock, newStock }
      });
      stock = newStock;
    }

    await writeHistory({
      type: 'PACKET_TEMPLATE_UPDATED',
      description: `Updated packet template: ${name} (${size} kg/${unit})`,
      userId: user.id,
      userName,
      details: { productId: product.id, ...fields }
    });

    revalidatePath('/factory');
    return { success: true, id: product.id, stock };
  } catch (err) {
    return fail(err);
  }
}

export async function deletePacketProduct(productId: string, deletePassword: string): Promise<ActionResult> {
  try {
    const pwError = checkDeletePassword(deletePassword);
    if (pwError) return { error: pwError };
    const { user, role, userName } = await enforceFactoryAccess();
    if (!['admin', 'manager'].includes(role)) {
      return { error: 'Only admins and managers can delete product templates.' };
    }
    if (productId === 'p-variance') {
      return { error: 'System variance tracking ledger cannot be deleted.' };
    }

    const { data: deleted, error } = await supabaseAdmin
      .from('factory_packet_catalog')
      .delete()
      .eq('id', productId)
      .select('name, stock')
      .maybeSingle();

    if (error) return { error: error.message };
    if (!deleted) return { error: 'Product not found.' };

    await writeHistory({
      type: 'PACKET_TEMPLATE_DELETED',
      description: `Deleted packet template: ${deleted.name} (stock at deletion: ${deleted.stock})`,
      userId: user.id,
      userName,
      details: { productId, productName: deleted.name, stockAtDeletion: Number(deleted.stock) }
    });

    revalidatePath('/factory');
    return { success: true };
  } catch (err) {
    return fail(err);
  }
}

export async function receivePacketStock(data: {
  productId: string;
  quantity: number;
  date: string;
}): Promise<ActionResult<{ newStock: number }>> {
  try {
    const { user, role, userName } = await enforceFactoryAccess();
    if (!['admin', 'manager'].includes(role)) {
      return { error: 'Only admins and managers can receive packaged stock.' };
    }
    const qty = positive(data.quantity, 'Quantity');

    // Atomic increment + history in one transaction (fn_receive_packet_stock)
    const { data: newStock, error } = await supabaseAdmin.rpc('fn_receive_packet_stock', {
      p_product_id: data.productId,
      p_qty: qty,
      p_date: isoDate(data.date),
      p_user_id: user.id,
      p_user_name: userName
    });
    if (error) return { error: error.message };

    revalidatePath('/factory');
    return { success: true, newStock: Number(newStock) };
  } catch (err) {
    return fail(err);
  }
}

