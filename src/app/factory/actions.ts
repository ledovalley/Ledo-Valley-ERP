/** Purge lots with no weight left. Lots still holding tea, system ledgers, and
 *  lots used by blends under process are never touched. */
export async function purgeNilLooseLots(deletePassword: string): Promise<ActionResult<{ count: number; message?: string }>> {
  try {
    const pwError = checkDeletePassword(deletePassword);
    if (pwError) return { error: pwError };
    const { user, role, userName } = await enforceFactoryAccess();
    if (!['admin', 'manager'].includes(role)) {
      return { error: 'Only admins and managers can purge empty stock.' };
    }

    const { data: candidates, error: fetchErr } = await supabaseAdmin
      .from('factory_loose_lots')
      .select('id, lot_number, mark, bags, weight')
      .lte('weight', 0)
      .not('id', 'in', `(${SYSTEM_LOT_IDS.join(',')})`);

    if (fetchErr) return { error: fetchErr.message };

    const inUse = await lotIdsInPendingBlends();
    type LotRow = { id: string; lot_number: string; mark: string };
    const lotsToDelete = ((candidates || []) as LotRow[]).filter(l => !inUse.has(l.id));

    if (lotsToDelete.length === 0) {
      return { success: true, count: 0, message: 'No empty lots found to purge.' };
    }

    const ids = lotsToDelete.map(l => l.id);

    // Re-check weight in the delete itself, in case stock was added meanwhile
    const { data: deleted, error: deleteErr } = await supabaseAdmin
      .from('factory_loose_lots')
      .delete()
      .in('id', ids)
      .lte('weight', 0)
      .select('id, lot_number, mark');

    if (deleteErr) return { error: deleteErr.message };

    const count = deleted?.length ?? 0;
    await writeHistory({
      type: 'NIL_STOCK_PURGED',
      description: `Purged ${count} empty loose tea lots.`,
      userId: user.id,
      userName,
      details: { count, lots: ((deleted || []) as LotRow[]).map(l => `${l.mark} (${l.lot_number})`) }
    });

    revalidatePath('/factory');
    return { success: true, count };
  } catch (err) {
    return fail(err);
  }
}

