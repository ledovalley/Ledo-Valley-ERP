export async function fetchFactoryHistory(limit: number = 300, offset: number = 0) {
  await enforceFactoryAccess();
  const supabase = await createClient();

  const safeLimit = Math.min(Math.max(1, Math.floor(limit) || 300), 2000);
  const safeOffset = Math.max(0, Math.floor(offset) || 0);

  const { data, error } = await supabase
    .from('factory_history')
    .select('*')
    .order('timestamp', { ascending: false })
    .range(safeOffset, safeOffset + safeLimit - 1);

  if (error) {
    console.error('Error fetching factory history:', error);
    throw new Error('Could not load factory history. Please refresh.');
  }

  return data || [];
}

export type LotUsageRow = {
  blendId: string;
  blendName: string;
  batchNo: string;
  status: string;
  date: string;
  /** when the blend was packed (PACKED only) */
  packedAt: string | null;
  bagsUsed: number;
  weightUsed: number;
};

export type LotCorrection = {
  date: string;
  /** LOT_STOCK_CORRECTED (edit form) or LEDGER_ADJUSTMENT */
  type: string;
  deltaKg: number;
  description: string;
  userName: string | null;
};

/**
 * Received + corrections + returns - used in blends = expected stock.
 * receivedKg is null when there is no receipt record (e.g. lots that existed
 * before records were kept); the screen then works the opening figure out.
 */
export type LotReconciliation = {
  receivedKg: number | null;
  receivedAt: string | null;
  corrections: LotCorrection[];
  correctionsKg: number;
  returnsKg: number;
  usedKg: number;
};

/**
 * Lot audit trail: every blend that used this lot and how much, read from the
 * blend lot records (not the history list), so nothing is missed however old.
 * A merged blend that used the lot more than once shows as one row with the total.
 * Deleted blends are not listed because their stock went back to the lot.
 */
export async function fetchLotUsage(
  lotId: string
): Promise<{ rows: LotUsageRow[]; reconciliation: LotReconciliation } | { error: string }> {
  try {
    await enforceFactoryAccess();
    const supabase = await createClient();

    const { data, error } = await supabase
      .from('factory_blend_lots_used')
      .select('blend_id, bags_used, weight_used, factory_blends!inner(id, blend_name, batch_no, status, date, created_at, updated_at)')
      .eq('lot_id', required(lotId, 'Lot'));

    if (error) return { error: error.message };

    const byBlend = new Map<string, LotUsageRow & { createdAt: string }>();
    for (const row of (data || []) as any[]) {
      // the embedded blend can come back as an object or a one-item array
      const b = Array.isArray(row.factory_blends) ? row.factory_blends[0] : row.factory_blends;
      if (!b) continue;
      const existing = byBlend.get(b.id);
      const bags = lotId.startsWith('l-') ? 0 : Number(row.bags_used) || 0;
      const kg = Number(row.weight_used) || 0;
      if (existing) {
        existing.bagsUsed += bags;
        existing.weightUsed += kg;
      } else {
        byBlend.set(b.id, {
          blendId: b.id,
          blendName: b.blend_name,
          batchNo: b.batch_no || '',
          status: b.status,
          date: b.date,
          packedAt: b.status === 'PACKED' ? b.updated_at : null,
          bagsUsed: bags,
          weightUsed: kg,
          createdAt: b.created_at
        });
      }
    }

    const rows = Array.from(byBlend.values())
      .sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt)))
      .map(({ createdAt: _createdAt, ...r }) => ({ ...r, weightUsed: Number(r.weightUsed.toFixed(3)) }));

    // --- Stock reconciliation from the full history (not just the recent 300 rows)
    const q = `"${lotId.replace(/"/g, '')}"`;
    const { data: events, error: histErr } = await supabase
      .from('factory_history')
      .select('type, timestamp, description, user_name, details')
      .in('type', ['LOT_ADDED', 'LOT_STOCK_CORRECTED', 'LEDGER_ADJUSTMENT'])
      .or(`details->>id.eq.${q},details->>lotId.eq.${q},details->>target_id.eq.${q}`)
      .order('timestamp', { ascending: true });
    if (histErr) return { error: histErr.message };

    let receivedKg: number | null = null;
    let receivedAt: string | null = null;
    const corrections: LotCorrection[] = [];
    for (const e of (events || []) as any[]) {
      const d = e.details || {};
      if (e.type === 'LOT_ADDED') {
        if (receivedKg === null && Number.isFinite(Number(d.weight))) {
          receivedKg = Number(d.weight);
          receivedAt = e.timestamp;
        }
        continue;
      }
      let delta = NaN;
      if (e.type === 'LOT_STOCK_CORRECTED') {
        delta = Number(d.after?.weight) - Number(d.before?.weight);
      } else if (e.type === 'LEDGER_ADJUSTMENT') {
        delta = Number(d.new_weight) - Number(d.prev_weight);
        if (!Number.isFinite(delta)) delta = Number(d.adjustment_amount ?? d.amount);
      }
      if (!Number.isFinite(delta) || delta === 0) continue;
      corrections.push({
        date: e.timestamp,
        type: e.type,
        deltaKg: Number(delta.toFixed(3)),
        description: e.description,
        userName: e.user_name ?? null
      });
    }

    // Loose tea returned when blends were finalized (only ever into the return lot)
    let returnsKg = 0;
    if (lotId === 'l-balance' || lotId.startsWith('l-')) {
      const returnFilter = lotId === 'l-balance'
        ? `details->>returnLotId.eq.${q},details->>returnLotId.is.null`
        : `details->>returnLotId.eq.${q}`;
      const { data: packs, error: packErr } = await supabase
        .from('factory_history')
        .select('details')
        .eq('type', 'BLEND_PACKED')
        .or(returnFilter);
      if (packErr) return { error: packErr.message };
      returnsKg = (packs || []).reduce((sum: number, p: any) => sum + (Number(p.details?.returnedLooseWeight) || 0), 0);
    }

    const usedKg = rows.reduce((sum, r) => sum + r.weightUsed, 0);
    const correctionsKg = corrections.reduce((sum, c) => sum + c.deltaKg, 0);

    return {
      rows,
      reconciliation: {
        receivedKg,
        receivedAt,
        corrections,
        correctionsKg: Number(correctionsKg.toFixed(3)),
        returnsKg: Number(returnsKg.toFixed(3)),
        usedKg: Number(usedKg.toFixed(3))
      }
    };
  } catch (err) {
    return fail(err);
  }
}

/**
 * Gap Analysis: serial numbers that were never issued between SL-01 and the
 * highest serial. Computed from the whole database, not just recent history.
 */
export async function fetchMissingSerials(): Promise<string[]> {
  const { role } = await enforceFactoryAccess();
  if (!['admin', 'manager'].includes(role)) return [];

  const { data, error } = await supabaseAdmin.from('factory_issued_serials').select('serial_no');
  if (error) {
    console.error('Error fetching issued serials:', error);
    return [];
  }

  const issued = new Set<number>((data || []).map((r: { serial_no: number }) => Number(r.serial_no)));
  const max = issued.size ? Math.max(...issued) : 0;
  const missing: string[] = [];
  for (let i = 1; i <= max; i++) {
    if (!issued.has(i)) missing.push(`SL-${String(i).padStart(2, '0')}`);
  }
  return missing;
}

