// A small Excel (.xlsx) writer: several sheets, bold rows, money and number
// formats, column widths. No library needed (an .xlsx file is a zip of XML files;
// this writes the zip uncompressed, which Excel, Google Sheets and LibreOffice open).

export type XCell =
  | string
  | number
  | null
  | undefined
  | { v: string | number | null | undefined; s?: XStyle }

/** 0 plain, 1 bold, 2 money/2 decimals, 3 bold + money, 4 header (bold, shaded), 5 title (bold, larger) */
export type XStyle = 0 | 1 | 2 | 3 | 4 | 5

export type XSheet = {
  name: string
  rows: XCell[][]
  widths?: number[] // characters
}

const enc = new TextEncoder()

function esc(s: string) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    // characters not allowed in XML
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
}

function colName(i: number) {
  let s = ''
  i += 1
  while (i > 0) {
    const m = (i - 1) % 26
    s = String.fromCharCode(65 + m) + s
    i = Math.floor((i - 1) / 26)
  }
  return s
}

/** Sheet names: max 31 characters, no : \ / ? * [ ], unique (case-insensitive). */
export function safeSheetNames(names: string[]) {
  const used = new Set<string>()
  return names.map(n => {
    const base = (n.replace(/[:\\/?*[\]]/g, ' ').replace(/\s+/g, ' ').trim() || 'Sheet').slice(0, 31)
    let name = base
    for (let k = 2; used.has(name.toLowerCase()); k++) {
      const suffix = ` (${k})`
      name = base.slice(0, 31 - suffix.length) + suffix
    }
    used.add(name.toLowerCase())
    return name
  })
}

function sheetXml(sheet: XSheet) {
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>`
    : ''
  const rows = sheet.rows.map((row, r) => {
    const cells = row.map((cell, c) => {
      const ref = `${colName(c)}${r + 1}`
      const obj = cell !== null && typeof cell === 'object' ? cell : { v: cell as any, s: 0 as XStyle }
      const v = obj.v
      const s = obj.s ?? 0
      const st = s ? ` s="${s}"` : ''
      if (v === null || v === undefined || v === '') return s ? `<c r="${ref}"${st}/>` : ''
      if (typeof v === 'number' && Number.isFinite(v)) return `<c r="${ref}"${st}><v>${v}</v></c>`
      return `<c r="${ref}"${st} t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`
    }).join('')
    return `<row r="${r + 1}">${cells}</row>`
  }).join('')
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${cols}<sheetData>${rows}</sheetData></worksheet>`
}

