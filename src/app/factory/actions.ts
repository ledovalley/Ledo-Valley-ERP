// Must match the /factory rule in src/utils/supabase/middleware.ts.
const FACTORY_ROLES = ['admin', 'manager'];

// Not exported: a "use server" file may only export async functions.
const SYSTEM_LOT_IDS = ['l-balance', 'l-orthodox', 'l-cardamom', 'l-cardamom-husk'];

async function enforceFactoryAccess() {
  const user = await getCachedUser();
  const role = user?.app_metadata?.role as string | undefined;

  if (!user || !role || !FACTORY_ROLES.includes(role)) {
    throw new Error('Unauthorized: Insufficient permissions for factory operations.');
  }

  return { user, role, userName: (user.user_metadata?.name as string) || user.email || 'Unknown' };
}

type ActionResult<T = object> = ({ success: true } & T) | { success?: false; error: string };

// -----------------------------------------------------------------------------
// Small validation helpers
// -----------------------------------------------------------------------------
function toNumber(value: unknown): number {
  const n = typeof value === 'number' ? value : parseFloat(String(value ?? ''));
  return Number.isFinite(n) ? n : NaN;
}

function positive(value: unknown, label: string): number {
  const n = toNumber(value);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`${label} must be a number greater than 0.`);
  return n;
}

function nonNegative(value: unknown, label: string): number {
  const n = toNumber(value);
  if (!Number.isFinite(n) || n < 0) throw new Error(`${label} must be 0 or more.`);
  return n;
}

function required(value: unknown, label: string): string {
  const s = String(value ?? '').trim();
  if (!s) throw new Error(`${label} is required.`);
  return s;
}

function isoDate(value: unknown): string {
  const s = String(value ?? '').trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(s) ? s : new Date().toISOString().split('T')[0];
}

function newId(prefix: string) {
  return `${prefix}-${crypto.randomUUID()}`;
}

async function writeHistory(entry: {
  type: string;
  description: string;
  userId: string;
  userName: string;
  details?: Record<string, unknown>;
}) {
  // id is generated by the database
  const { error } = await supabaseAdmin.from('factory_history').insert({
    type: entry.type,
    description: entry.description,
    user_id: entry.userId,
    user_name: entry.userName,
    details: entry.details ?? {}
  });
  if (error) console.error('Factory history write failed:', entry.type, error);
}

function fail(err: unknown): { error: string } {
  const message = err instanceof Error ? err.message : String(err);
  return { error: message };
}

