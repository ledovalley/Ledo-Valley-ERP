// Blends (all stock changes happen inside SQL transactions)
// -----------------------------------------------------------------------------
type BlendLotInput = { lotId: string; bagsUsed: number | string; weightUsed: number };

function cleanLots(lots: BlendLotInput[]) {
  if (!Array.isArray(lots) || lots.length === 0) throw new Error('Select at least one lot.');
  const seenIds = new Set<string>();
  return lots.map(l => {
    const lotId = required(l.lotId, 'Lot');
    if (seenIds.has(lotId)) throw new Error(`Lot ${lotId} is selected twice.`);
    seenIds.add(lotId);
    const isSystem = lotId.startsWith('l-');
    const bags = isSystem ? 0 : toNumber(l.bagsUsed);
    if (!isSystem && (!Number.isInteger(bags) || bags < 0)) {
      throw new Error('Bags used must be a whole number.');
    }
    return { lotId, bagsUsed: bags, weightUsed: positive(l.weightUsed, 'Weight used') };
  });
}

